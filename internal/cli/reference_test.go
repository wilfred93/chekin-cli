package cli

import (
	"bytes"
	"context"
	"flag"
	"os"
	"strings"
	"testing"
)

// The docs site's command reference is built from the CLI's own help text, so
// it can't drift from the binary. After changing a command or flag, run:
//
//	go test ./internal/cli -run TestCommandReference -update
var update = flag.Bool("update", false, "rewrite the docs command reference")

const referencePath = "../../docs/src/content/docs/reference/commands.md"

// referenceCommands are the commands documented on the reference page, in order.
var referenceCommands = []struct {
	title string
	args  []string
}{
	{"chekin", []string{"help"}},
	{"chekin login", []string{"login", "--help"}},
	{"chekin logout", []string{"logout", "--help"}},
	{"chekin whoami", []string{"whoami", "--help"}},
	{"chekin bookings list", []string{"bookings", "list", "--help"}},
	{"chekin bookings get", []string{"bookings", "get", "--help"}},
	{"chekin version", nil},
}

func renderReference(t *testing.T) []byte {
	t.Helper()
	// Defaults shown in help text come from the environment; keep them out.
	for _, k := range []string{"CHEKIN_EMAIL", "CHEKIN_PASSWORD", "CHEKIN_TOKEN", "CHEKIN_API_URL", "CHEKIN_CONFIG_DIR"} {
		t.Setenv(k, "")
	}

	var b strings.Builder
	b.WriteString(`---
title: Command reference
description: Every chekin command and flag, generated from the CLI's help text.
---

<!-- Generated by internal/cli/reference_test.go. Don't edit by hand; run
     go test ./internal/cli -run TestCommandReference -update -->

This page is generated from the help text built into ` + "`chekin`" + `, so it always matches the
code in the repository. Run ` + "`chekin <command> --help`" + ` to see the same text in your terminal.

Flags take one dash or two (` + "`-o json`" + ` and ` + "`--o json`" + ` are the same) and go after the
command name. ` + "`reservations`" + ` works anywhere ` + "`bookings`" + ` does.
`)
	for _, c := range referenceCommands {
		b.WriteString("\n## `" + c.title + "`\n\n")
		if c.args == nil {
			b.WriteString("Prints `chekin` and the version. `--version` does the same. Builds that don't set a version at build time (including `go install` and `go build`) print `chekin dev`.\n")
			continue
		}
		var out bytes.Buffer
		app := &App{Stdin: strings.NewReader(""), Stdout: &out, Stderr: &out}
		if code := app.Run(context.Background(), c.args); code != 0 {
			t.Fatalf("chekin %s: exit code %d\n%s", strings.Join(c.args, " "), code, out.String())
		}
		help, noFlags := strings.CutSuffix(out.String(), "\nFlags:\n")
		b.WriteString("```text\n" + strings.ReplaceAll(help, "\t", "    ") + "```\n")
		if noFlags {
			b.WriteString("\nNo flags.\n")
		}
	}
	return []byte(b.String())
}

func TestCommandReference(t *testing.T) {
	want := renderReference(t)
	if *update {
		if err := os.WriteFile(referencePath, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(referencePath)
	if err != nil {
		t.Fatalf("%v\nrun: go test ./internal/cli -run TestCommandReference -update", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is out of date with the CLI's help text\nrun: go test ./internal/cli -run TestCommandReference -update", referencePath)
	}
}
